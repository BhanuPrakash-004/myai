import { NextRequest } from "next/server";
import { z } from "zod";
import { knowledge } from "@/lib/storage/knowledge";
import { AttachmentService } from "@/lib/storage/attachments";
import { readStorageConfig } from "@/lib/storage/config";
import { importMarkdown, importPolicy, previewImport } from "@/lib/storage/imports";
import { privateRoute,readBody,operationKey } from "@/lib/http";
import { DomainError } from "@/lib/storage/access";
import { ok } from "@/lib/api";
export const runtime="nodejs";
export const POST=privateRoute(async(r:NextRequest)=>{
 const key=operationKey(r),bounded=new Request(r.url,{method:"POST",headers:r.headers,body:await readBody(r,11*1024*1024)});
 const form=await bounded.formData(),file=form.get("file");
 if(!(file instanceof File)) throw new DomainError("MISSING_FILE","Select a Markdown, text, code or ZIP file.");
 const service=knowledge(),files=new AttachmentService(service.pool,readStorageConfig().DATA_DIR);
 const destination=form.get("folderId");
 const folderId=destination===null?undefined:z.guid().parse(destination),bytes=Buffer.from(await file.arrayBuffer());
 if(form.get("action")==="preview") return ok(await previewImport(service,bytes,file.name,folderId));
 const policy=importPolicy.parse(form.get("policy") || "error");
 const expectedVersions=z.record(z.string(),z.number().int().positive()).parse(JSON.parse(String(form.get("expectedVersions") || "{}")));
 return ok(await importMarkdown(service,files,bytes,file.name,key,folderId,{policy,expectedVersions}));
});
